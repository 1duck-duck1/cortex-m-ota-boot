/**
 ******************************************************************************
 * @file    boot_main.h
 * @brief   Boot 的启动流程入口：决策 + 跳转 + 升级模式主循环
 *
 * 启动顺序刻意定成"先处理请求、后做决策"：NVS 里的升级请求与邮箱里的回 Boot
 * 请求都可能在本次启动改变"该跑哪个槽"的结论，先决策再处理就会把刚收好的
 * 固件忽略掉。因此顺序是：消费确认 → 复核 NVS 请求 → 决策 → 跳转或进升级模式。
 *
 * Direct-XIP 下 Boot 从不搬运镜像，只决定"跑哪一份"和"要不要先升级"。
 ******************************************************************************
 */
#ifndef BOOT_MAIN_H
#define BOOT_MAIN_H

/**
 * @brief  Boot 的完整启动流程
 * @note   本函数永不返回：要么跳进 App，要么停在升级模式的主循环里。
 *         main() 在时钟与 HAL 初始化完成后调用它，之后不再回到 main。
 */
void boot_main(void);

#endif /* BOOT_MAIN_H */
